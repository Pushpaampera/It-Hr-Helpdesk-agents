"""Builds and persists the real-time SSE event stream (docs/01_ARCHITECTURE.md's event schema),
including the plain-English `caption` narrator string for every event — generated by templates
here, never by an extra LLM call (master prompt section 0.7, point 2).
"""
import asyncio
import json
import uuid
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import text

from app import observability
from app.db import get_engine

FRIENDLY_NAMES = {
    "guard": "Gus",
    "supervisor": "Sage",
    "it_support": "Iris",
    "hr_policy": "Hana",
    "action": "Atlas",
    "ticketing": "Tess",
    "feedback": "Finn",
}

AGENT_JOBS = {
    "guard": "the Privacy Guardian",
    "supervisor": "the Request Router",
    "it_support": "the IT Specialist",
    "hr_policy": "the HR Policy Expert",
    "action": "the Task Doer",
    "ticketing": "the Case Handler",
    "feedback": "the Quality Keeper",
}


def _name(agent: str) -> str:
    return FRIENDLY_NAMES.get(agent, agent.title())


# ---- caption templates: pure functions of (agent, status, action, detail) -> plain English ----

def build_caption(agent: str, status: str, action: str | None, detail: dict | None) -> str:
    name = _name(agent)
    detail = detail or {}

    if agent == "guard":
        if status == "working":
            return f"{name} is checking this request for anything sensitive."
        if detail.get("blocked"):
            return f"{name} stopped this request: {detail.get('reason', 'it touched someone else’s private data.')}"
        return f"{name} checked the request and found nothing sensitive."

    if agent == "supervisor":
        if status == "working":
            return f"{name} is reading your message and deciding who can help best."
        if status == "completed":
            route = detail.get("route")
            if route == "OTHER":
                return f"{name} wasn't sure who should help, so is asking a quick clarifying question."
            friendly = {"IT": "Iris, the IT Specialist", "HR": "Hana, the HR Policy Expert"}.get(route, route)
            conf = detail.get("confidence")
            conf_txt = f" ({int(conf * 100)}% confident)" if isinstance(conf, (int, float)) else ""
            return f"{name} routed this to {friendly}{conf_txt}."

    if agent in ("it_support", "hr_policy"):
        dept = "IT runbooks" if agent == "it_support" else "HR policy handbook"
        if status == "retrieving":
            return f"{name} is checking the {dept} for the best match."
        if status == "working":
            return f"{name} is putting together an answer."
        if status == "completed":
            if detail.get("unresolved"):
                return f"{name} couldn't find a confident answer in the knowledge base."
            return f"{name} answered with a cited source."

    if agent == "action":
        tool = detail.get("tool")
        tool_captions = {
            "reset_password": f"{name} is resetting the password.",
            "unlock_account": f"{name} is unlocking the account.",
            "apply_leave": f"{name} is submitting the leave request.",
            "get_leave_balance": f"{name} is looking up the leave balance.",
            "request_access": f"{name} is requesting access and needs a manager's approval.",
        }
        if status == "tool_call" and tool in tool_captions:
            return tool_captions[tool]
        if status == "completed" and tool:
            return f"{name} finished: {tool.replace('_', ' ')} completed."
        if status == "working":
            return f"{name} is deciding what action to take."

    if agent == "ticketing":
        if status == "working":
            return f"{name} is writing up a summary for a human to review."
        if status == "completed":
            number = detail.get("ticket_number", "")
            return f"{name} created ticket {number} with the full story so a human can take over."

    if agent == "feedback":
        if status == "started":
            return f"{name} is waiting to hear how that went."
        if status == "completed":
            return f"{name} logged your feedback and is learning from it."

    return f"{name}, {AGENT_JOBS.get(agent, '')} — {status}."


_LIVE_QUEUES: dict[str, "asyncio.Queue"] = {}


def get_queue(run_id: str) -> "asyncio.Queue | None":
    return _LIVE_QUEUES.get(run_id)


def drop_queue(run_id: str) -> None:
    _LIVE_QUEUES.pop(run_id, None)


class EventSink:
    """One instance per agent run. Persists every event to agent_events and, if a live queue is
    attached, pushes the same event onto it for the SSE endpoint to stream in real time."""

    def __init__(self, run_id: str, queue: "asyncio.Queue | None" = None, start_seq: int = 0):
        self.run_id = run_id
        self.queue = queue
        self.seq = start_seq
        if queue is not None:
            _LIVE_QUEUES[run_id] = queue

    def _ts(self) -> str:
        return datetime.now(timezone.utc).isoformat()

    async def _publish(self, event: dict) -> None:
        if self.queue is not None:
            await self.queue.put(event)

    def _persist(self, agent: str | None, status: str | None, action: str | None, caption: str | None,
                 detail: dict, model: str | None, latency_ms: int | None, tokens_in: int, tokens_out: int) -> None:
        if agent is None:
            return
        engine = get_engine()
        with engine.begin() as conn:
            conn.execute(
                text(
                    """INSERT INTO agent_events
                       (run_id, seq, agent, status, action, caption, detail, model, latency_ms, tokens_in, tokens_out)
                       VALUES (:run_id, :seq, :agent, :status, :action, :caption, :detail, :model, :latency_ms, :tokens_in, :tokens_out)"""
                ),
                {
                    "run_id": self.run_id, "seq": self.seq, "agent": agent, "status": status, "action": action,
                    "caption": caption, "detail": json.dumps(detail), "model": model, "latency_ms": latency_ms,
                    "tokens_in": tokens_in, "tokens_out": tokens_out,
                },
            )

    async def emit(self, agent: str, status: str, action: str | None = None, detail: dict | None = None,
                    model: str | None = None, latency_ms: int | None = None, tokens_in: int = 0,
                    tokens_out: int = 0, caption: str | None = None) -> dict:
        self.seq += 1
        detail = detail or {}
        caption = caption or build_caption(agent, status, action, detail)
        event = {
            "run_id": self.run_id, "seq": self.seq, "type": "agent_event", "agent": agent, "status": status,
            "action": action, "caption": caption, "detail": detail, "model": model, "latency_ms": latency_ms,
            "tokens_in": tokens_in, "tokens_out": tokens_out, "ts": self._ts(),
        }
        self._persist(agent, status, action, caption, detail, model, latency_ms, tokens_in, tokens_out)
        observability.trace_event(self.run_id, agent, status, detail, latency_ms, model)
        await self._publish(event)
        return event

    async def emit_handoff(self, from_agent: str, to_agent: str, reason: str) -> dict:
        self.seq += 1
        event = {
            "run_id": self.run_id, "seq": self.seq, "type": "handoff", "from": from_agent, "to": to_agent,
            "reason": reason, "caption": f"{_name(from_agent)} handed this to {_name(to_agent)}: {reason}",
            "ts": self._ts(),
        }
        await self._publish(event)
        return event

    async def emit_token(self, text_chunk: str) -> dict:
        self.seq += 1
        event = {"run_id": self.run_id, "seq": self.seq, "type": "token", "text": text_chunk, "ts": self._ts()}
        await self._publish(event)
        return event

    async def emit_approval_required(self, approval_id: str, approver_name: str, system: str) -> dict:
        self.seq += 1
        event = {
            "run_id": self.run_id, "seq": self.seq, "type": "approval_required", "approval_id": approval_id,
            "approver_name": approver_name, "system": system,
            "caption": f"Atlas paused this request — it needs {approver_name}'s approval to access {system}.",
            "ts": self._ts(),
        }
        await self._publish(event)
        return event

    async def emit_final(self, answer: str, sources: list[dict], route: str | None, resolved: bool,
                          ticket_number: str | None = None) -> dict:
        # Stream the final answer as word-chunk "token" events first, for a typing effect.
        words = answer.split()
        chunk_size = 4
        for i in range(0, len(words), chunk_size):
            await self.emit_token(" ".join(words[i:i + chunk_size]) + " ")
            await asyncio.sleep(0.01)

        self.seq += 1
        event = {
            "run_id": self.run_id, "seq": self.seq, "type": "final", "answer": answer, "sources": sources,
            "route": route, "resolved": resolved, "ticket_number": ticket_number, "ts": self._ts(),
        }
        await self._publish(event)
        return event

    async def emit_error(self, message: str) -> dict:
        self.seq += 1
        event = {"run_id": self.run_id, "seq": self.seq, "type": "error", "message": message, "ts": self._ts()}
        await self._publish(event)
        return event


def new_run_id() -> str:
    return str(uuid.uuid4())


def load_events_for_run(run_id: str) -> list[dict]:
    """Replay support: GET /api/runs/{id}/events."""
    engine = get_engine()
    with engine.connect() as conn:
        rows = conn.execute(
            text(
                """SELECT run_id, seq, agent, status, action, caption, detail, model, latency_ms,
                   tokens_in, tokens_out, ts FROM agent_events WHERE run_id = :run_id ORDER BY seq"""
            ),
            {"run_id": run_id},
        ).mappings().all()
    events = []
    for r in rows:
        d = dict(r)
        d["run_id"] = str(d["run_id"])
        d["type"] = "agent_event"
        d["ts"] = d["ts"].isoformat()
        events.append(d)
    return events
